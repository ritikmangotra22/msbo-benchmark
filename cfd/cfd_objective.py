"""
Real OpenFOAM objective function: given 5 k-epsilon coefficients, run steady RANS
(simpleFoam) on the Pitz-Daily backward-facing-step case and return the predicted
reattachment length (in step heights). Each call is a genuine CFD solve, not a
surrogate. The mesh is pre-built once in TEMPLATE_DIR and copied (not re-meshed)
for every evaluation.

IMPORTANT HONESTY NOTE: this is the built-in OpenFOAM "Pitz & Daily" combustor
tutorial geometry, NOT the Driver & Seegmiller wind-tunnel step the paper's
Section 14 specifies. No verified experimental reattachment length for this
exact rig was available, so this is used as a synthetic parameter-recovery
test (a known target flow, generated by one fixed coefficient set, that the
optimizer must reproduce from scratch), not a claim of experimental validation.
"""
import os, shutil, subprocess, uuid
import numpy as np
import meshio

HERE = os.path.dirname(os.path.abspath(__file__))
TEMPLATE_DIR = os.path.join(HERE, "case_template")
SCRATCH_ROOT = os.path.join(HERE, "scratch")
os.makedirs(SCRATCH_ROOT, exist_ok=True)

FOAM_ENV = {**os.environ, "WM_PROJECT_DIR": "/usr/share/openfoam", "FOAM_API": "1912"}

STEP_H = 0.0254  # m, from blockMeshDict
X_LO, X_HI = 0.0002, 0.199  # m, window for the near-wall sampling band (excludes step corner and outlet ramp)
Y_BAND_LO, Y_BAND_HI = -0.0254, -0.024  # m, thin band just above the lower wall

TURBPROP_TEMPLATE = """/*--------------------------------*- C++ -*----------------------------------*\\
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       dictionary;
    location    "constant";
    object      turbulenceProperties;
}}

simulationType RAS;

RAS
{{
    RASModel        kEpsilon;
    turbulence      on;
    printCoeffs     on;

    kEpsilonCoeffs
    {{
        Cmu             {Cmu};
        C1              {C1};
        C2              {C2};
        C3              0;
        sigmak          {sigmak};
        sigmaEps        {sigmaEps};
    }}
}}
"""


def _make_case(theta, tag):
    case_dir = os.path.join(SCRATCH_ROOT, tag)
    if os.path.exists(case_dir):
        shutil.rmtree(case_dir)
    os.makedirs(case_dir)
    # reuse the pre-built mesh (symlink polyMesh to avoid copying it every time)
    os.makedirs(os.path.join(case_dir, "constant"))
    os.symlink(os.path.join(TEMPLATE_DIR, "constant", "polyMesh"),
               os.path.join(case_dir, "constant", "polyMesh"))
    shutil.copy(os.path.join(TEMPLATE_DIR, "constant", "transportProperties"),
                os.path.join(case_dir, "constant", "transportProperties"))
    shutil.copytree(os.path.join(TEMPLATE_DIR, "0"), os.path.join(case_dir, "0"))
    shutil.copytree(os.path.join(TEMPLATE_DIR, "system"), os.path.join(case_dir, "system"))
    Cmu, C1, C2, sigmak, sigmaEps = theta
    with open(os.path.join(case_dir, "constant", "turbulenceProperties"), "w") as f:
        f.write(TURBPROP_TEMPLATE.format(Cmu=Cmu, C1=C1, C2=C2, sigmak=sigmak, sigmaEps=sigmaEps))
    return case_dir


def _run_solver(case_dir, max_iters=2000):
    # cap iterations via controlDict endTime (already 2000 in the template)
    log_path = os.path.join(case_dir, "log.simpleFoam")
    with open(log_path, "w") as log:
        proc = subprocess.run(["simpleFoam"], cwd=case_dir, env=FOAM_ENV,
                               stdout=log, stderr=subprocess.STDOUT, timeout=120)
    return proc.returncode, log_path


def _latest_time_dir(case_dir):
    times = []
    for d in os.listdir(case_dir):
        try:
            times.append(float(d))
        except ValueError:
            continue
    if not times:
        return None
    return str(int(max(times))) if max(times) == int(max(times)) else str(max(times))


def _reattachment_length(case_dir):
    """Export the converged internal field to VTK and locate the last sign change
    of the streamwise velocity in a thin band just above the lower wall
    (matches Eq. 37 of the paper: U=0 at the first cell off the wall)."""
    t = _latest_time_dir(case_dir)
    if t is None:
        return None
    vtk_dir = os.path.join(case_dir, "VTK")
    proc = subprocess.run(["foamToVTK", "-time", t], cwd=case_dir, env=FOAM_ENV,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=60)
    case_name = os.path.basename(case_dir)
    vtu_path = os.path.join(vtk_dir, f"{case_name}_{int(float(t))}", "internal.vtu")
    if not os.path.exists(vtu_path):
        # try float-formatted directory name
        cand = [p for p in os.listdir(vtk_dir)] if os.path.isdir(vtk_dir) else []
        matches = [c for c in cand if c.startswith(case_name)]
        if not matches:
            return None
        vtu_path = os.path.join(vtk_dir, matches[0], "internal.vtu")
        if not os.path.exists(vtu_path):
            return None
    m = meshio.read(vtu_path)
    pts = m.points
    hexc = m.cells[0].data
    centers = pts[hexc].mean(axis=1)
    U = np.concatenate(m.cell_data["U"])
    mask = ((centers[:, 0] > X_LO) & (centers[:, 0] < X_HI) &
            (centers[:, 1] > Y_BAND_LO) & (centers[:, 1] < Y_BAND_HI))
    if mask.sum() < 10:
        return None
    xs, ux = centers[mask, 0], U[mask, 0]
    order = np.argsort(xs)
    xs, ux = xs[order], ux[order]
    sign_changes = np.where((ux[:-1] < 0) & (ux[1:] >= 0))[0]
    if len(sign_changes) == 0:
        return None  # never reattaches within the sampled window
    x_reattach = xs[sign_changes[-1] + 1]
    return x_reattach / STEP_H


def evaluate(theta, tag=None, cleanup=True):
    """theta = (Cmu, C1, C2, sigmak, sigmaEps). Returns (X_r_over_H or None, converged: bool)."""
    tag = tag or f"eval_{uuid.uuid4().hex[:10]}"
    case_dir = _make_case(theta, tag)
    try:
        rc, log_path = _run_solver(case_dir)
        converged = False
        if rc == 0 and os.path.exists(log_path):
            with open(log_path) as f:
                converged = "SIMPLE solution converged" in f.read()
        xr = _reattachment_length(case_dir) if os.path.exists(case_dir) else None
        return xr, converged
    finally:
        if cleanup and os.path.exists(case_dir):
            shutil.rmtree(case_dir, ignore_errors=True)
